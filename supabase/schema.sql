-- ==========================================================================
-- Supabase Auth 회원가입 자동 이메일 승인 및 public.profiles 닉네임 자동 동기화 트리거
-- ==========================================================================
CREATE OR REPLACE FUNCTION public.handle_hobak_auth_user_before_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  NEW.email_confirmed_at := COALESCE(NEW.email_confirmed_at, NOW());
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_hobak_auth_auto_confirm ON auth.users;
CREATE TRIGGER trg_hobak_auth_auto_confirm
  BEFORE INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_hobak_auth_user_before_insert();

CREATE OR REPLACE FUNCTION public.handle_hobak_auth_user_created()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_nickname TEXT;
BEGIN
  v_nickname := COALESCE(NULLIF(TRIM(NEW.raw_user_meta_data ->> 'nickname'), ''), split_part(NEW.email, '@', 1));
  INSERT INTO public.profiles (auth_user_id, nickname, avatar_bg, manner_temp, neighborhood)
  VALUES (NEW.id, v_nickname, '#FFE8CC', 36.5, '울산 동구 방어동')
  ON CONFLICT (nickname) DO UPDATE
    SET auth_user_id = EXCLUDED.auth_user_id;
  RETURN NEW;
EXCEPTION WHEN OTHERS THEN
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_hobak_on_auth_user_created ON auth.users;
CREATE TRIGGER trg_hobak_on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW
  EXECUTE FUNCTION public.handle_hobak_auth_user_created();

