-- 1. profiles: 판매자·이웃 가명 프로필 테이블 (실명/이메일/전화번호 미저장, Supabase Auth 연동)
CREATE TABLE IF NOT EXISTS public.profiles (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  auth_user_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  nickname TEXT NOT NULL UNIQUE,
  avatar_bg VARCHAR(20) NOT NULL DEFAULT '#FFE8CC',
  manner_temp NUMERIC(4,1) NOT NULL DEFAULT 36.5,
  neighborhood VARCHAR(50) NOT NULL DEFAULT '울산 동구 방어동',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public.profiles ADD COLUMN IF NOT EXISTS auth_user_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE;

COMMENT ON TABLE public.profiles IS '호박 중고거래 이웃 가명 프로필 (Supabase Auth UUID와 닉네임만 매핑)';

-- 2. products: 중고거래 상품 목록·상세·글쓰기 핵심 테이블
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  seller_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
  seller_nickname TEXT NOT NULL DEFAULT '호박이웃',
  seller_manner_temp NUMERIC(4,1) NOT NULL DEFAULT 37.5,
  seller_avatar_bg VARCHAR(20) NOT NULL DEFAULT '#FFE8CC',
  title VARCHAR(100) NOT NULL,
  category VARCHAR(40) NOT NULL DEFAULT '디지털기기',
  price INTEGER NOT NULL DEFAULT 0 CHECK (price >= 0),
  is_free BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT '판매중',
  quick_buy BOOLEAN NOT NULL DEFAULT FALSE,
  location VARCHAR(30) NOT NULL DEFAULT '방어동',
  full_location VARCHAR(60) NOT NULL DEFAULT '울산 동구 방어동',
  images JSONB NOT NULL DEFAULT '[]'::jsonb,
  description TEXT NOT NULL DEFAULT '',
  likes_count INTEGER NOT NULL DEFAULT 0,
  chats_count INTEGER NOT NULL DEFAULT 0,
  views_count INTEGER NOT NULL DEFAULT 1,
  is_bumped BOOLEAN NOT NULL DEFAULT FALSE,
  time_ago VARCHAR(30) NOT NULL DEFAULT '방금 전',
  liked BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.products IS '호박 중고거래 상품 정보 테이블';

-- 3. product_likes: 관심(하트 ♥) 토글 기록 테이블 (익명 브라우저 UUID 기반)
CREATE TABLE IF NOT EXISTS public.product_likes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  viewer_anon_id UUID NOT NULL DEFAULT gen_random_uuid(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (product_id, viewer_anon_id)
);

COMMENT ON TABLE public.product_likes IS '익명 브라우저 UUID 기반 상품 관심(하트) 기록';

-- 4. chat_messages: 호박 미니 채팅 메시지 테이블 (전화번호 노출 없이 앱 내 대화)
CREATE TABLE IF NOT EXISTS public.chat_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id BIGINT NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  sender_role VARCHAR(20) NOT NULL DEFAULT 'buyer',
  sender_nickname VARCHAR(50) NOT NULL DEFAULT '호박이웃',
  message TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.chat_messages IS '호박 미니 채팅 대화 내역 (연락처 노출 없는 비식별 채팅)';

-- 5. popular_keywords: 우측 사이드바 인기 검색어 집계 테이블
CREATE TABLE IF NOT EXISTS public.popular_keywords (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  keyword VARCHAR(40) NOT NULL UNIQUE,
  search_count INTEGER NOT NULL DEFAULT 1,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.popular_keywords IS '호박 중고거래 인기 검색어 알약 태그 목록';

-- 인덱스 생성
CREATE INDEX IF NOT EXISTS idx_products_seller_id ON public.products USING btree (seller_id);
CREATE INDEX IF NOT EXISTS idx_products_status_created ON public.products USING btree (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products USING btree (category);
CREATE INDEX IF NOT EXISTS idx_products_images_gin ON public.products USING gin (images);
CREATE INDEX IF NOT EXISTS idx_product_likes_product_id ON public.product_likes USING btree (product_id);
CREATE INDEX IF NOT EXISTS idx_chat_messages_product_id ON public.chat_messages USING btree (product_id, created_at ASC);

-- Row Level Security (RLS) 활성화
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.product_likes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.popular_keywords ENABLE ROW LEVEL SECURITY;

-- RLS 정책 생성 (중복 오류 방지 DO 블록)
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'profiles' AND policyname = 'Public read profiles') THEN
    CREATE POLICY "Public read profiles" ON public.profiles FOR SELECT TO anon, authenticated USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'profiles' AND policyname = 'Public insert profiles') THEN
    CREATE POLICY "Public insert profiles" ON public.profiles FOR INSERT TO anon, authenticated WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'profiles' AND policyname = 'Public update profiles') THEN
    CREATE POLICY "Public update profiles" ON public.profiles FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'products' AND policyname = 'Public read products') THEN
    CREATE POLICY "Public read products" ON public.products FOR SELECT TO anon, authenticated USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'products' AND policyname = 'Public insert products') THEN
    CREATE POLICY "Public insert products" ON public.products FOR INSERT TO anon, authenticated WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'products' AND policyname = 'Public update products') THEN
    CREATE POLICY "Public update products" ON public.products FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'products' AND policyname = 'Public delete products') THEN
    CREATE POLICY "Public delete products" ON public.products FOR DELETE TO anon, authenticated USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'product_likes' AND policyname = 'Public manage product_likes') THEN
    CREATE POLICY "Public manage product_likes" ON public.product_likes FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'chat_messages' AND policyname = 'Public manage chat_messages') THEN
    CREATE POLICY "Public manage chat_messages" ON public.chat_messages FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'popular_keywords' AND policyname = 'Public read popular_keywords') THEN
    CREATE POLICY "Public read popular_keywords" ON public.popular_keywords FOR SELECT TO anon, authenticated USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname = 'public' AND tablename = 'popular_keywords' AND policyname = 'Public update popular_keywords') THEN
    CREATE POLICY "Public update popular_keywords" ON public.popular_keywords FOR UPDATE TO anon, authenticated USING (true) WITH CHECK (true);
  END IF;
END $$;

